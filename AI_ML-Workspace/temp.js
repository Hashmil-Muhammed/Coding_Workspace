function selectRole(role, text) {
    currentRole = role;
    document.getElementById('selectedRoleText').innerText = text;
    document.getElementById('roleDropdown').classList.remove('active');
    
    // Update active class on dropdown items
    const items = document.querySelectorAll('.dropdown-item');
    items.forEach(item => {
        if (item.innerText.includes(role) || (role === 'All' && item.innerText.includes('All'))) {
            item.classList.add('selected');
        } else {
            item.classList.remove('selected');
        }
    });

    currentPhaseIndex = 0; // Reset
    renderSidebar();
    
    // Auto-select first visible
    const visiblePhases = roadmapData.filter(phase => roleMapping[currentRole].includes(phase.phase));
    if (visiblePhases.length > 0) {
        const firstVisibleIndex = roadmapData.findIndex(phase => phase.phase === visiblePhases[0].phase);
        if (firstVisibleIndex !== -1) {
            currentPhaseIndex = firstVisibleIndex;
            renderPhase(currentPhaseIndex);
        }
    }
}

function renderSidebar() {
    const sidebar = document.getElementById('nav-items');
    sidebar.innerHTML = '';
    
    roadmapData.forEach((phase, index) => {
        if (!roleMapping[currentRole].includes(phase.phase)) return;
        
        const item = document.createElement('div');
        item.className = `nav-item ${index === currentPhaseIndex ? 'active' : ''}`;
        item.innerHTML = `<div><strong>${phase.phase}</strong><div style="font-size:0.8rem; opacity:0.8">${phase.title.substring(0,35)}...</div></div>`;
        item.onclick = () => { currentPhaseIndex = index; renderSidebar(); renderPhase(index); };
        sidebar.appendChild(item);
    });
}


function renderNode(node, depth, parentPath) {
    if (typeof node === 'string') return `<li class="leaf-node"><span class="bullet">➔</span> ${node}</li>`;
    const path = parentPath ? `${parentPath}-${node.name.replace(/\W+/g, '')}` : node.name.replace(/\W+/g, '');
    const isChecked = userProgress[path] ? 'checked' : '';
    const completedClass = userProgress[path] ? 'completed' : '';
    
    let html = `
        <div class="nested-card depth-${depth} ${completedClass}" id="node-${path}">
            <div class="nested-header" onclick="toggleNode('${path}')">
                <div style="display:flex; align-items:center; gap:0.5rem;">
                    <span class="chevron" id="icon-${path}">➔</span>
                    <input type="checkbox" ${isChecked} onclick="event.stopPropagation(); toggleProgress('${path}')">
                    <span class="node-title">${node.name}</span>
                </div>
            </div>
            <div class="nested-body" id="body-${path}">
    `;
    if (node.children && node.children.length > 0) {
        html += `<ul class="children-list">`;
        node.children.forEach(child => { html += renderNode(child, depth + 1, path); });
        html += `</ul>`;
    }
    if(node.interview || node.practice || node.resources) {
        html += `<div class="node-details">`;
        if (node.interview) html += `<h5>💡 Interview Prep</h5><ul>${node.interview.map(i => `<li>${i}</li>`).join('')}</ul>`;
        if (node.practice) html += `<h5>💻 Practice</h5><ul>${node.practice.map(p => `<li>${p}</li>`).join('')}</ul>`;
        if (node.resources) html += `<h5>📚 Resources</h5><div class="tags">${node.resources.map(r => `<span class="tag">${r}</span>`).join('')}</div>`;
        html += `</div>`;
    }
    html += `</div></div>`;
    return html;
}

function renderProjects(projectsObj) {
    if(!projectsObj) return '';
    let html = `<div class="projects-section">`;
    const tiers = ['beginner', 'intermediate', 'advanced'];
    tiers.forEach(tier => {
        if(projectsObj[tier] && projectsObj[tier].length > 0) {
            html += `<h3 class="tier-title">Top 5 ${tier.charAt(0).toUpperCase() + tier.slice(1)} Projects</h3><div class="top5-grid">`;
            projectsObj[tier].forEach((p, i) => {
                html += `
                    <div class="top5-card ${tier}">
                        <div class="top5-number">${i+1}</div>
                        <h4>${p.name}</h4>
                        <div style="font-size: 0.85rem; color: var(--text-secondary); margin-bottom: 0.5rem;">Key Concepts:</div>
                        <div class="tags">${p.uses.map(u => `<span class="tag tool">${u}</span>`).join('')}</div>
                    </div>
                `;
            });
            html += `</div>`;
        }
    });
    html += `</div>`;
    return html;
}



function renderChecklists(checklists, phaseIndex) {
    if(!checklists) return '';
    let html = `<div class="checklists-section"><h3 style="margin-bottom: 1.5rem; font-size: 1.5rem; color: #fff;">Phase Completion Checklists</h3><div class="checklist-grid">`;
    
    Object.keys(checklists).forEach(category => {
        html += `<div class="checklist-col"><h4>${category.toUpperCase()} CHECKLIST</h4>`;
        checklists[category].forEach((item, i) => {
            const key = `chk-${phaseIndex}-${category}-${i}`;
            const isChecked = userProgress[key] ? 'checked' : '';
            html += `
                <div class="checklist-item ${isChecked}" id="item-${key}">
                    <input type="checkbox" ${isChecked} onchange="toggleChecklist('${key}')">
                    <span>${item}</span>
                </div>
            `;
        });
        html += `</div>`;
    });
    html += `</div></div>`;
    return html;
}


function renderResources(resources) {
    if (!resources || resources.length === 0) return '';
    let html = `<div class="resources-section"><h3 style="font-size: 1.5rem; color: #fff; margin-bottom: 0.5rem;">Recommended Resources</h3><div class="resources-grid">`;
    resources.forEach(r => {
        html += `
            <a href="${r.link}" target="_blank" class="resource-card">
                <div class="resource-type">${r.type}</div>
                <div class="resource-name">${r.name}</div>
                <div class="resource-icon">↗</div>
            </a>
        `;
    });
    html += `</div></div>`;
    return html;
}

function renderPhase(index) {
    const phase = roadmapData[index];
    if(!phase) { document.getElementById('content-area').innerHTML = `<h2>Under Construction</h2>`; return; }
    let html = `<div class="header-card"><h1 class="header-title">${phase.phase}: ${phase.title}</h1><p style="font-size: 1.1rem; color: var(--text-secondary);">${phase.overview.why}</p></div>`;
    phase.skills.forEach(skill => { html += renderNode(skill, 0, `p${index}`); });
    html += renderResources(phase.resources);
    html += renderProjects(phase.projects);
    html += renderChecklists(phase.checklists, index);
    document.getElementById('content-area').innerHTML = html;
}

