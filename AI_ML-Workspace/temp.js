// UI Logic
let currentPhaseIndex = 0;
let userProgress = JSON.parse(localStorage.getItem('aiml_roadmap_progress')) || {};

function getProgressStats() {
    let totalNodes = 0;
    let checkedNodes = 0;
    const phaseStats = [];

    roadmapData.forEach((phase, index) => {
        if (!roleMapping[currentRole].includes(phase.phase)) return;
        let pTotal = 0;
        let pChecked = 0;
        
        function traverse(node, parentPath, depth) {
            if (typeof node === 'string') return;
            const path = parentPath ? `${parentPath}-${node.name.replace(/\W+/g, '')}` : node.name.replace(/\W+/g, '');
            
            if (depth <= 1) {
                pTotal++;
                totalNodes++;
                
                if (userProgress[path]) {
                    pChecked++;
                    checkedNodes++;
                }
            }
            
            if (node.children) {
                node.children.forEach(child => traverse(child, path, depth + 1));
            }
        }
        
        phase.skills.forEach(skill => traverse(skill, `p${index}`, 0));
        phaseStats.push({ total: pTotal, checked: pChecked, name: phase.phase, originalIndex: index });
    });
    
    return { totalNodes, checkedNodes, phaseStats };
}

function resetAllProgress() {
    if (confirm('Are you sure you want to reset all progress?')) {
        userProgress = {};
        localStorage.removeItem('aiml_roadmap_progress');
        renderDashboard();
        renderPhase(currentPhaseIndex);
    }
}

